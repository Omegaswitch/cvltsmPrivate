"""
Traces the loader's engraving into SVG paths (components/loader-paths.ts):
its outer silhouette and the larger shapes inside it, simplified, so the
loader can draw them in blood. Needs opencv-python-headless and numpy.

  python scripts/make-loader.py assets/engravings/1-87.png
"""
import os, sys, cv2, numpy as np

src = sys.argv[1] if len(sys.argv) > 1 else 'assets/engravings/1-87.png'
W = 600                                   # working width; the viewBox is in these units

img = cv2.imread(src, cv2.IMREAD_UNCHANGED)
if img.ndim == 3 and img.shape[2] == 4:  # transparent paper: ink is where alpha is
    a = img[:, :, 3].astype(np.float32) / 255
    g = cv2.cvtColor(img[:, :, :3], cv2.COLOR_BGR2GRAY).astype(np.float32)
    img = (g * a + 255 * (1 - a)).astype(np.uint8)
elif img.ndim == 3:
    img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
h = round(img.shape[0] * W / img.shape[1])
img = cv2.resize(img, (W, h), interpolation=cv2.INTER_AREA)
ink = (img < 140).astype(np.uint8) * 255

def contours(mask, close, mode, smooth=0):
    k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (close, close))
    m = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, k)
    if smooth:                            # round off the hatching's teeth
        m = (cv2.GaussianBlur(m, (smooth, smooth), 0) > 127).astype(np.uint8) * 255
    cs, _ = cv2.findContours(m, mode, cv2.CHAIN_APPROX_NONE)
    return cs

def path(c, eps):
    c = cv2.approxPolyDP(c, eps, True).reshape(-1, 2)
    return 'M' + ' L'.join(f'{x} {y}' for x, y in c) + ' Z'

outer = max(contours(ink, 15, cv2.RETR_EXTERNAL, 9), key=cv2.contourArea)
inner = [c for c in contours(ink, 5, cv2.RETR_LIST, 5) if cv2.arcLength(c, True) > 160]
inner = sorted(inner, key=lambda c: -cv2.arcLength(c, True))[1:14]   # the first is the outline again

paths = [path(outer, 1.2)] + [path(c, 1.4) for c in inner]
with open('components/loader-paths.ts', 'w') as f:
    f.write('// generated by scripts/make-loader.py from %s; do not edit\n' % src)
    f.write('export const SRC = \'/engravings/%s.webp\';\n' % os.path.splitext(os.path.basename(src))[0])
    f.write('export const VIEW = \'0 0 %d %d\';\n' % (W, h))
    f.write('export const PATHS = [\n' + ''.join(f"  '{p}',\n" for p in paths) + '];\n')
print(len(paths), 'paths', sum(len(p) for p in paths), 'chars')
