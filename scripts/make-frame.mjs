// Draws the outline that surrounds a kit, a render or a colour: not a frame,
// just two uneven lines scratched round it, broken in places, overshooting
// at the corners, as if drawn by hand a long time ago.
// Output: public/textures/frame.svg, used as a nine-slice border-image (slice
// 40 of 200), so it fits any size.
// Usage: node scripts/make-frame.mjs
import { writeFileSync } from 'node:fs';

// a seeded random, so the outline is the same every time it is drawn
let s = 0x2545f491;
const rand = () => { s ^= s << 13; s ^= s >>> 17; s ^= s << 5; return ((s >>> 0) % 100000) / 100000; };
const r = (a, b) => a + rand() * (b - a);
const f = (n) => n.toFixed(1);

const S = 200;

/** One side of an outline, as a few separate wavering strokes with gaps between. */
function side(x1, y1, x2, y2, opts) {
  const { width, opacity, gaps } = opts;
  const len = Math.hypot(x2 - x1, y2 - y1);
  // cut points along the side: pieces are drawn, the spaces between are the gaps
  const cuts = [0];
  for (let i = 0; i < gaps; i++) cuts.push(r(0.12, 0.9));
  cuts.push(1);
  cuts.sort((a, b) => a - b);
  let out = '';
  for (let i = 0; i < cuts.length - 1; i += 2) {
    const a = cuts[i], b = Math.max(cuts[i + 1] - r(0.01, 0.04), a + 0.04);
    const steps = Math.max(3, Math.round((b - a) * 12));
    const pts = [];
    for (let k = 0; k <= steps; k++) {
      const u = a + ((b - a) * k) / steps;
      const w = r(-1.6, 1.6);
      const nx = -(y2 - y1) / len, ny = (x2 - x1) / len;
      pts.push(`${f(x1 + (x2 - x1) * u + nx * w)} ${f(y1 + (y2 - y1) * u + ny * w)}`);
    }
    out += `<path d="M${pts.join(' L')}" fill="none" stroke="#d4ccbf" stroke-width="${f(width * r(0.8, 1.25))}" stroke-linecap="round" stroke-linejoin="round" opacity="${f(opacity * r(0.75, 1))}"/>`;
  }
  return out;
}

/** A loose rectangle: each side a little off true, overshooting its corners. */
function loop(inset, opts) {
  const o = () => r(-3, 3);
  const over = () => r(2, 9);
  const a = inset + o(), b = S - inset + o();
  const c = inset + o(), d = S - inset + o();
  return [
    side(a - over(), c + o(), b + over(), c + o(), opts),          // top
    side(b + o(), c - over(), b + o(), d + over(), opts),          // right
    side(b + over(), d + o(), a - over(), d + o(), opts),          // bottom
    side(a + o(), d + over(), a + o(), c - over(), opts),          // left
  ].join('');
}

const body = loop(11, { width: 3.4, opacity: 0.62, gaps: 3 }) + loop(21, { width: 2.4, opacity: 0.32, gaps: 4 });

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}" width="${S}" height="${S}">
  <!-- Generated by scripts/make-frame.mjs; do not edit by hand. -->
  <defs>
    <filter id="rough" x="-5%" y="-5%" width="110%" height="110%">
      <feTurbulence type="fractalNoise" baseFrequency="0.09" numOctaves="2" seed="7" result="n"/>
      <feDisplacementMap in="SourceGraphic" in2="n" scale="3.2" xChannelSelector="R" yChannelSelector="G"/>
    </filter>
  </defs>
  <g filter="url(#rough)">${body}</g>
</svg>
`;
writeFileSync('public/textures/frame.svg', svg);
console.log('public/textures/frame.svg', svg.length, 'bytes');
